import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:gymmane/app/gymmane_app.dart';
import 'package:gymmane/l10n/l10n.dart';
import 'package:gymmane/services/local_store.dart';
import 'package:gymmane/state/fit_state.dart';
import 'package:gymmane/theme/app_colors.dart';
import 'package:shared_preferences/shared_preferences.dart';

void main() {
  testWidgets('settings switches the live palette and keeps dark and system modes independent', (tester) async {
    SharedPreferences.setMockInitialValues({});
    await Store.instance.init();
    fit.resetAllData();
    fit.onboarded = true;
    fit.setLanguage('zh');
    setAppLanguage('zh');
    fit.setThemePref('light');
    fit.calmMotion = true;
    fit.gamification = false;
    fit.lowEndAsked = true;
    fit.route = 'preferences';
    tester.view.physicalSize = const Size(390, 844);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    addTearDown(tester.platformDispatcher.clearPlatformBrightnessTestValue);
    await tester.pumpWidget(const GymManeApp());
    await tester.pump(const Duration(seconds: 2));
    await tester.tap(find.text('通用').first);
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    final row = find.byKey(const ValueKey('settings-light-palette'));
    GymColors colors() => Theme.of(tester.element(row)).extension<GymColors>()!;
    expect(colors().bg, GymColors.light.bg);
    await tester.tap(row);
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    await tester.tap(find.text('原版暖米灰').last);
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    expect(fit.lightPalette, 'original');
    expect(colors().bg, GymColors.lightOriginal.bg);
    fit.persistNow();
    fit.lightPalette = 'sage';
    fit.loadFromStore();
    expect(fit.lightPalette, 'original');
    for (final mode in ['dark', 'amoled']) {
      fit.setThemePref(mode);
      await tester.pump();
      await tester.pump(const Duration(seconds: 1));
      final expected = mode == 'amoled' ? GymColors.amoled : GymColors.dark;
      expect(colors().bg, expected.bg);
      fit.setLightPalette('sage');
      await tester.pump();
      await tester.pump(const Duration(seconds: 1));
      expect(colors().bg, expected.bg);
      fit.setLightPalette('original');
    }
    tester.platformDispatcher.platformBrightnessTestValue = Brightness.light;
    fit.setThemePref('system');
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    expect(colors().bg, GymColors.lightOriginal.bg);
    tester.platformDispatcher.platformBrightnessTestValue = Brightness.dark;
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    expect(colors().bg, GymColors.dark.bg);
    fit.setThemePref('light');
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    await tester.tap(row);
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    await tester.tap(find.text('鼠尾草白').last);
    await tester.pump();
    await tester.pump(const Duration(seconds: 1));
    expect(colors().bg, GymColors.light.bg);
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox());
    await tester.pump(const Duration(seconds: 2));
  });
}
